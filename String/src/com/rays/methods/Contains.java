package com.rays.methods;

public class Contains {
	public static void main(String[] args) {
		
		String s1="javascript";

		System.out.println(s1);
		
		System.out.println("\nContains java: "+s1.contains("java"));
		
		System.out.println("Contains javaaa: "+s1.contains("javaaa"));
		
//		Output:
//		javascript
//
//		Contains java: true
//		Contains javaaa: false
	}
}
