package com.rays.methods;

public class IndexOf {
	
	public static void main(String[] args) {
		
		String s1="Apurvaa";
		
		System.out.println(s1);
		
		System.out.println("Index of A: "+s1.indexOf("Ap"));
		
		System.out.println("Index of a: "+s1.indexOf("a"));
		
		System.out.println("Index of a: "+s1.lastIndexOf("a"));
		
//		Output:Apurva
//		Index of A: 0
//		Index of a: 5
//		Index of a: 6
	}
}
